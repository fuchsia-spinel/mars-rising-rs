#!/usr/bin/env python3
"""Golden vectors for the group-wipe bonus 0x29edc (src/pickup.rs `bonus_kind`) by running the original routine in ppcemu.py.

    python3 -I gen_bonus_vectors.py MarsRising.pef OUT.txt [seed] [n]

Line:  owner counter1 counter2 raw_random x_bits y_bits -> counter1' counter2' <log>
`counterN` is the word at +352 of player N's struct (0xc458 / 0xc2c0), `raw_random` the value Random() would hand to 0xa0d4 (queue of one).
Mocked: 0xa0d4 (logged `rnd_lo_hi_value`) and the pickup spawner 0x2a040 (logged `spawn_kind_variant_param_announce_xbits_ybits`)."""
import sys, os, random, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ppcemu

M32 = 0xffffffff
P1, P2 = 0xc458, 0xc2c0


def s32(v): return v - (1 << 32) if v & 0x80000000 else v
def f32bits(x): return struct.unpack('>I', struct.pack('>f', x))[0]


def main(exe, out, seed=1, n=400):
    rng = random.Random(seed)
    c = ppcemu.load(exe)
    base = bytes(c.mem)
    log = []
    q = []

    def rnd(cpu):
        lo, hi = s32(cpu.r[3]), s32(cpu.r[4])
        raw = q.pop(0)
        v = lo + raw % (hi - lo + 1)
        log.append('rnd_%d_%d_%d' % (lo, hi, v))
        cpu.r[3] = v & M32

    def spawn(cpu):
        log.append('spawn_%s_%08x_%08x' % ('_'.join(str(s32(cpu.r[i])) for i in (5, 6, 7, 8)), f32bits(cpu.getf(1)), f32bits(cpu.getf(2))))

    c.mocks.update({0xa0d4: rnd, 0x2a040: spawn})
    lines = []
    for _ in range(n):
        owner = rng.choice([1, 2, 1, 2, 0, 3])
        c1, c2 = rng.choice([0, 1, 5, 6, 7, 8, 9, 10, 12, -1]), rng.choice([0, 1, 5, 6, 7, 8, 9, 10, 12, -1])
        raw = rng.getrandbits(16)
        xb, yb = f32bits(rng.uniform(-50, 500)), f32bits(rng.uniform(-50, 600))
        c.mem[:] = base
        c.ww(P1 + 352, c1 & M32); c.ww(P2 + 352, c2 & M32)
        del log[:]; q[:] = [raw]
        c.setf(1, struct.unpack('>f', struct.pack('>I', xb))[0]); c.setf(2, struct.unpack('>f', struct.pack('>I', yb))[0])
        c.call(0x29edc, [0, 0, owner])
        lines.append('%d %d %d %d %08x %08x -> %d %d %s' % (owner, c1, c2, raw, xb, yb, s32(c.rw(P1 + 352)), s32(c.rw(P2 + 352)), ','.join(log)))
    with open(out, 'w') as f:
        f.write('# generated by tools/re/gen_bonus_vectors.py from the original executable; do not edit\n')
        f.write('\n'.join(lines) + '\n')
    return len(lines)


if __name__ == '__main__':
    print(main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 1, int(sys.argv[4]) if len(sys.argv) > 4 else 400), 'vectors')
