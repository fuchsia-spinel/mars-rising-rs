#!/usr/bin/env python3
"""Golden vectors for `PickupPool::convert_coins` (0x2b73c: the coins left on the screen turn into explosions when the level's coin bonus ends) by running the
original code in ppcemu.py.

    python3 -I gen_coins_vectors.py MarsRising.pef OUT.txt [seed] [n_vectors]

State: the pickup pool (20 x 128 bytes, pointer D.0fc4) and its counter D.1754. Mocked: the effect spawner 0x22670 (logged with the float arguments as bit patterns).
A vector line: `seed=.. pool=<hex of the 20 records> count=<n> -> h<pool hash>.<count> <logged calls>` (one operation only, the converter).
"""
import sys, os, random, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ppcemu
from gen_enemy_vectors import fnv64, s32, f32bits, M32

PTR, COUNT, N, SZ = 0xfc4, 0x1754, 20, 128


def gen(exe, out, seed=1, n=60):
    rng = random.Random(seed)
    c = ppcemu.load(exe)
    c.keep_toc = True
    log = []

    def eff(cpu):
        log.append('fx_%s_%08x_%08x' % ('_'.join(str(s32(cpu.r[i])) for i in range(3, 10)), cpu.getfbits(1), cpu.getfbits(2)))
    c.mocks[0x22670] = eff
    c.r[2] = 0x8000
    base_mem = bytes(c.mem)
    pool = c.rw(PTR)
    lines = []
    for it in range(n):
        c.mem[:] = base_mem
        log.clear()
        rec = bytearray()
        active = 0
        for i in range(N):
            r = bytearray(SZ)
            for k in range(0, SZ, 4):
                r[k:k + 4] = struct.pack('>I', rng.getrandbits(32) if rng.random() < 0.3 else 0)
            r[0] = 1 if rng.random() < 0.7 else rng.choice([0, 2, 255])
            r[8:12] = struct.pack('>I', rng.choice([2, 2, 20, 20, 3, 5, 0, 19, 21, 1, 22]))
            r[16:20] = struct.pack('>I', f32bits(rng.uniform(-40, 460)))
            r[20:24] = struct.pack('>I', f32bits(rng.uniform(-40, 520)))
            r[24:28] = struct.pack('>I', f32bits(rng.choice([0.0, rng.uniform(-3, 3)])))
            r[28:32] = struct.pack('>I', f32bits(rng.choice([0.0, rng.uniform(-3, 3)])))
            r[40:44] = struct.pack('>I', rng.choice([0, 1, 7, 15, 16, 17, 20, 31, 32, 0xffffffff, 0xfffffff1]))
            r[44:48] = struct.pack('>I', rng.choice([0, 1, 7, 15, 16, 17, 20, 31, 32]))
            r[60] = rng.choice([0, 0, 1, 2, 255])
            rec += r
            if r[0]:
                active += 1
        cnt = rng.choice([active, active, rng.randint(0, 25)])
        c.mem[pool:pool + N * SZ] = rec
        c.ww(COUNT, cnt)
        c.call(0x2b73c, [])
        h = 'h%016x.%d' % (fnv64(c.mem[pool:pool + N * SZ]), s32(c.rw(COUNT)))
        lines.append('seed=%d pool=%s count=%d -> %s' % (seed, rec.hex(), cnt, ' '.join([h] + log)))
    with open(out, 'w') as f:
        f.write('# generated by tools/re/gen_coins_vectors.py from the original executable; do not edit\n')
        f.write('\n'.join(lines) + '\n')
    return len(lines)


if __name__ == '__main__':
    exe, out = sys.argv[1], sys.argv[2]
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    n = int(sys.argv[4]) if len(sys.argv) > 4 else 60
    print(gen(exe, out, seed, n), 'vectors ->', out)
