#!/usr/bin/env python3
"""Derives src/ground_init.rs from the original executable: the per-kind initialisation 0x3b9b0 of a ground-object record.

The routine is a jump table of straight-line stores (animation index, frame, speed constants, hit box flags, ...) selected by the record's kind (+8),
variant (+76) and whether it has a predecessor link (+92 != -1). It reads nothing else, so it is run for every combination on two records pre-filled with
0x00 and 0xFF; a byte whose value differs in either run was written, and its final value is the table entry.

    python3 -I gen_ground_init.py MarsRising.pef ../../src/ground_init.rs
"""
import sys, os, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ppcemu

POOL, REC = 0x1a818, 168
IDX = 7


def run(c, base, kind, variant, linked, fill):
    a = POOL + IDX * REC
    c.mem[:] = base
    c.mem[a:a + REC] = bytes([fill]) * REC
    c.ww(a + 8, kind)
    c.ww(a + 76, variant)
    c.ww(a + 92, 3 if linked else 0xffffffff)
    pre = bytes(c.mem[a:a + REC])
    c.call(0x3b9b0, [IDX])
    return pre, bytes(c.mem[a:a + REC])


def entries(c, base, kind, variant, linked):
    out = {}
    for fill in (0x00, 0xff):
        pre, post = run(c, base, kind, variant, linked, fill)
        for i in range(REC):
            if post[i] != pre[i]:
                out[i] = post[i]
    # fields the routine did not write but which equal the pattern in both runs cannot exist; the fields we seeded are not written by it
    for off in (8, 76, 92):
        for i in range(off, off + 4):
            out.pop(i, None)
    return out


def compress(bytes_by_off):
    """Merge into (offset, length, value) with length 4 for aligned fully written words, 1 otherwise."""
    items, done = [], set()
    for off in sorted(bytes_by_off):
        if off in done: continue
        if off % 4 == 0 and all(o in bytes_by_off for o in range(off, off + 4)):
            v = 0
            for o in range(off, off + 4): v = (v << 8) | bytes_by_off[o]; done.add(o)
            items.append((off, 4, v))
        else:
            items.append((off, 1, bytes_by_off[off])); done.add(off)
    return items


def main(exe, out):
    c = ppcemu.load(exe)
    c.keep_toc = True
    c.r[2] = 0x8000
    base = bytes(c.mem)
    table, seen, order = {}, {}, []
    for kind in range(0, 26):
        for variant in range(0, 10):
            for linked in (0, 1):
                items = tuple(compress(entries(c, base, kind, variant, linked)))
                if items not in seen:
                    seen[items] = len(order); order.append(items)
                table[(kind, variant, linked)] = seen[items]
    # Out-of-range values: kinds above 25 behave like 25; variants above 9 like 9, except that some kinds copy the variant itself into +56 / +84
    # (kinds 16..21 keep it as their frame); those offsets are listed in VARIANT_COPY and overwritten with the variant.
    vcopy = {}
    for linked in (0, 1):
        for kind in (26, 30, 1000):
            assert tuple(compress(entries(c, base, kind, 3, linked))) == tuple(compress(entries(c, base, 25, 3, linked))), kind
        for kind in range(26):
            ref = dict((o, (l, v)) for o, l, v in compress(entries(c, base, kind, 9, linked)))
            for variant in (10, 12, 1000, 0xffffffff):
                got = dict((o, (l, v)) for o, l, v in compress(entries(c, base, kind, variant, linked)))
                assert set(got) == set(ref), (kind, variant)
                diff = sorted(o for o in got if got[o] != ref[o])
                for o in diff:
                    assert got[o] == (4, variant), (kind, variant, o, got[o])
                    assert ref[o] == (4, 9), (kind, o, ref[o])
                assert vcopy.setdefault((kind, linked), diff) == diff, (kind, variant)
    lines = ['//! GENERATED by tools/re/gen_ground_init.py from the original executable (0x3b9b0): do not edit.',
             '//!', '//! Per-kind initialisation of a ground-object record. Each set is a list of `(offset, length, value)` stores (length 4 = big-endian word,',
             '//! 1 = byte). `set_for(kind, variant, linked)` picks the set exactly as the original jump tables do; kinds above 25 and variants above 9',
             '//! behave like 25 and 9 (checked against the original when this file was generated).', '',
             'pub type Store = (u8, u8, u32);', '']
    for n, items in enumerate(order):
        lines.append('const S%d: &[Store] = &[%s];' % (n, ', '.join('(%d, %d, 0x%x)' % it for it in items)))
    lines += ['', 'const KIND_VARIANT_LINKED: [[[u8; 2]; 10]; 26] = [']
    for kind in range(26):
        lines.append('    [' + ', '.join('[%d, %d]' % (table[(kind, v, 0)], table[(kind, v, 1)]) for v in range(10)) + '],')
    lines += ['];', '', 'const SETS: &[&[Store]] = &[' + ', '.join('S%d' % i for i in range(len(order))) + '];', '',
              'const VARIANT_COPY: [[&[u8]; 2]; 26] = [' + ', '.join('[&%s, &%s]' % (vcopy[(k, 0)], vcopy[(k, 1)]) for k in range(26)) + '];',
              '',
              '/// Offsets that receive the variant itself when it is above 9 (the table holds the variant-9 values there).',
              'pub fn variant_copy(kind: u32, linked: bool) -> &\'static [u8] { VARIANT_COPY[kind.min(25) as usize][linked as usize] }',
              '',
              '/// The stores for a record of `kind` / `variant`; `linked` = it has a predecessor (`+92 != -1`).',
              'pub fn set_for(kind: u32, variant: u32, linked: bool) -> &\'static [Store] {',
              '    let k = kind.min(25) as usize;',
              '    let v = variant.min(9) as usize;',
              '    SETS[KIND_VARIANT_LINKED[k][v][linked as usize] as usize]', '}', '']
    # The two muzzle tables (24 x (first, second) s16) that 0x3a998 fills at level start: D.1090 = A (towers), D.1094 = B (turrets).
    c.mem[:] = base
    c.call(0x3a998, [])
    for name, addr in (('MUZZLE_A', 0x1a758), ('MUZZLE_B', 0x1a7b8)):
        pairs = []
        for k in range(24):
            f, s2 = c.rh(addr + 4 * k), c.rh(addr + 4 * k + 2)
            pairs.append('(%d, %d)' % (f - 65536 if f > 32767 else f, s2 - 65536 if s2 > 32767 else s2))
        lines += ['/// Muzzle offsets per animation frame: `(first, second)` = (dy, dx) from the record position (D.%s).' % ('1090' if name == 'MUZZLE_A' else '1094'),
                  'pub const %s: [(i16, i16); 24] = [%s];' % (name, ', '.join(pairs)), '']
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(len(order), 'distinct sets')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
