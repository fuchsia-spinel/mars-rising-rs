#!/usr/bin/env python3
"""Golden vectors for src/blit.rs by running the original sprite blitters in ppcemu.py.

    python3 -I gen_blit_vectors.py MarsRising.pef OUT.txt [seed] [n_per_prim]

The six blitters (called with r3 = compiled sprite, r4 = x, r5 = y, destination pitch D.81ac, base D.81b0):
    anim 0x3f08 | trans 0x4078 | dither 0x486c | shadow 0x46a8 | flash 0x4a90 | cast 0x444c
The compiled sprite is the original's run stream: s16 width, 2 bytes, then 4-byte commands [cmd][u24 n]
(1 = n literal pixels padded to 4, 2 = n transparent pixels, 3 = end of row, 4 = end of sprite). Real streams always use maximal, non-empty,
alternating runs that cover the whole row (checked over all 1248 sprites), and so do the generated ones.

Line:  prim=<p> w=<w> h=<h> x=<x> y=<y> seed=<u32> R=<rows> -> A=<hex of the 40x24 canvas after>
rows: '/' between rows, ',' between runs, `S<n>` = n transparent pixels, `L<hex bytes>` = literal pixels.
The canvas before the call is lcg(seed); tables: flash[i] = 5i+17, shadow[i] = 11i+3 (mod 256), blend[d*256+s] = 13d+7s (mod 256).
"""
import sys, os, random, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ppcemu

CW, CH = 40, 24
FB, SPR, TB, HND = 0x200000, 0x300000, 0x280000, 0x270000
ADDR = {'anim': 0x3f08, 'trans': 0x4078, 'dither': 0x486c, 'shadow': 0x46a8, 'flash': 0x4a90, 'cast': 0x444c}


def flash_lut(i): return (5 * i + 17) & 255
def shadow_lut(i): return (11 * i + 3) & 255
def blend(d, s): return (13 * d + 7 * s) & 255


def lcg_canvas(seed):
    out = bytearray(); s = seed & 0xffffffff
    for _ in range(CW * CH):
        s = (s * 1664525 + 1013904223) & 0xffffffff
        out.append((s >> 24) & 255)
    return bytes(out)


def stream(w, rows):
    out = bytearray(struct.pack('>HH', w, 0))
    for r in rows:
        for kind, val in r:
            if kind == 'L':
                out += struct.pack('>I', (1 << 24) | len(val)) + bytes(val) + b'\0' * ((4 - len(val) % 4) % 4)
            else:
                out += struct.pack('>I', (2 << 24) | val)
        out += struct.pack('>I', 3 << 24)
    out += struct.pack('>I', 4 << 24)
    return bytes(out)


def rand_rows(rng, w, h, style):
    rows = []
    for _ in range(h):
        runs = []; x = 0; kind = rng.random() < 0.5
        while x < w:
            if style == 'dense': n = rng.randint(1, w - x) if rng.random() < 0.3 else w - x
            elif style == 'fine': n = rng.randint(1, min(3, w - x))
            else: n = rng.randint(1, w - x)
            runs.append(('L', [rng.randrange(256) for _ in range(n)]) if kind else ('S', n))
            x += n; kind = not kind
        rows.append(runs)
    return rows


def rows_str(rows):
    return '/'.join(','.join(('L' + bytes(v).hex()) if k == 'L' else 'S%d' % v for k, v in r) for r in rows)


def gen(exe, out, seed=1, n=120):
    rng = random.Random(seed)
    cpu = ppcemu.load(exe)
    base = bytes(cpu.mem)
    lines = []
    for prim, addr in ADDR.items():
        for it in range(n):
            w = rng.randint(1, 13) if it % 4 else rng.choice([1, 2, 3, 4, 5, 8, 12])
            h = rng.randint(1, 9)
            rows = rand_rows(rng, w, h, rng.choice(['mixed', 'dense', 'fine']))
            x = rng.randint(0, CW - w); y = rng.randint(0, CH - h)
            sd = rng.getrandbits(32)
            cpu.mem[:] = base
            cpu.ww(0x81ac, CW); cpu.ww(0x81b0, FB)
            cv = lcg_canvas(sd)
            cpu.mem[FB:FB + CW * CH] = cv
            data = stream(w, rows)
            cpu.mem[SPR:SPR + len(data)] = data
            for i in range(256):
                cpu.ww(0x8204 + 4 * i, flash_lut(i))
                cpu.ww(0x8604 + 4 * i, shadow_lut(i))
            cpu.ww(35332, HND); cpu.ww(HND, TB)
            cpu.mem[TB:TB + 65536] = bytes(blend(i >> 8, i & 255) for i in range(65536))
            cpu.call(addr, [SPR, x, y])
            after = bytes(cpu.mem[FB:FB + CW * CH])
            lines.append('prim=%s w=%d h=%d x=%d y=%d seed=%d R=%s -> A=%s' % (prim, w, h, x, y, sd, rows_str(rows), after.hex()))
    with open(out, 'w') as f:
        f.write('# generated by tools/re/gen_blit_vectors.py from the original executable; do not edit\n')
        f.write('\n'.join(lines) + '\n')
    return len(lines)


if __name__ == '__main__':
    exe, out = sys.argv[1], sys.argv[2]
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    n = int(sys.argv[4]) if len(sys.argv) > 4 else 120
    print(gen(exe, out, seed, n), 'vectors ->', out)
