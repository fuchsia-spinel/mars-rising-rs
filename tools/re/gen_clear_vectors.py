#!/usr/bin/env python3
"""Golden vectors for pickup::clear_reward (0xea4c: the reward when the last ground target of a level is destroyed). Runs the original routine with
random ship states / armor levels (ship byte +1 = state, +172 = armor level) and difficulty D.13ec; 0x2a040 is mocked and logged.

    python3 -I gen_clear_vectors.py MarsRising.pef OUT.txt [seed] [n]
line: `S1=<state>,<armor> S2=<state>,<armor> D=<difficulty> -> <logged spawn call or ->`"""
import sys, os, random, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ppcemu
from gen_enemy_vectors import s32, f32bits

P1, P2, DIF = 0xc458, 0xc2c0, 0x13ec


def gen(exe, out, seed=1, n=1000):
    rng = random.Random(seed)
    c = ppcemu.load(exe)
    c.keep_toc = True
    log = []

    def spawn(cpu):
        log.append('spawn_%d_%d_%d_%d' % tuple(s32(cpu.r[i]) for i in (5, 6, 7, 8)) + '_%08x_%08x' % (f32bits(cpu.getf(1)), f32bits(cpu.getf(2))))
    c.mocks[0x2a040] = spawn
    c.r[2] = 0x8000
    base = bytes(c.mem)
    lines = []
    for _ in range(n):
        c.mem[:] = base
        log.clear()
        st = [rng.choice([3, 3, 3, 3, 0, 1, 2, 4]) for _ in range(2)]
        ar = [rng.choice([0, 1, 2, 3, 4, 5, 5, 6, 9, 200]) for _ in range(2)]
        dif = rng.choice([0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 25, rng.randint(0, 30)])
        for p, s_, a_ in ((P1, st[0], ar[0]), (P2, st[1], ar[1])):
            c.mem[p + 1] = s_; c.mem[p + 172] = a_
        c.ww(DIF, dif)
        x, y = float(rng.randint(0, 416)), float(rng.randint(-20, 480))
        c.setf(1, x); c.setf(2, y)
        c.call(0xea4c, [], [x, y])
        lines.append('S1=%d,%d S2=%d,%d D=%d X=%08x Y=%08x -> %s' % (st[0], ar[0], st[1], ar[1], dif, f32bits(x), f32bits(y), ','.join(log) or '-'))
    with open(out, 'w') as f:
        f.write('# generated by tools/re/gen_clear_vectors.py from the original executable; do not edit\n')
        f.write('\n'.join(lines) + '\n')
    return len(lines)


if __name__ == '__main__':
    print(gen(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 1, int(sys.argv[4]) if len(sys.argv) > 4 else 1000), 'vectors')
